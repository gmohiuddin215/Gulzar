#!/usr/bin/env python3
"""Write the substitution rules that turn typed honorifics into their glyphs.

    python3 scripts/honorific-ligatures.py

Typing صلی اللہ علیہ وسلم (with or without harakat, with or without the
spaces between the words, with the Arabic or the Urdu ye and he) gives the
single ﷺ glyph; likewise for every honorific drawn by the "honorifics" step
of scripts/nastaliq-reshape.py. The rules run first in ccmp, on the letters
as typed, so they work wherever the font shapes Urdu, with no feature to
switch on. A phrase inside a longer word (سلمان، اللہیار) is left alone, and
any harakat typed inside a phrase become an empty mark, honorificMark.

Writes sources/build/honorific-ligatures.fea, which the Makefile puts first
among the feature files.
"""
import itertools
import os
import unicodedata

import glyphsLib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCE = os.path.join(ROOT, "sources", "Gulzar.glyphs")
OUT = os.path.join(ROOT, "sources", "build", "honorific-ligatures.fea")
MARK = "honorificMark"

# letters typed in more than one way
ALTERNATIVES = {
    "ی": "یيى",
    "ہ": "ہه",
    "ۃ": "ۃةت",
    "آ": "آا",
}

# glyph: the phrases (words separated by spaces) that turn into it
PHRASES = {
    "sallallahuAlayhiWasallam": ["صلی اللہ علیہ و سلم"],
    "sallallahuAlayhiWaAalihiWasallam": ["صلی اللہ علیہ و آلہ و سلم"],
    "radiAllahuAnhu": ["رضی اللہ عنہ"],
    "radiAllahuAnhaa": ["رضی اللہ عنہا"],
    "radiAllahuAnhum": ["رضی اللہ عنہم"],
    "radiAllahuAnhumaa": ["رضی اللہ عنہما"],
    "radiAllahuAnhunna": ["رضی اللہ عنہن"],
    "rahmatullahAlayh": ["رحمۃ اللہ علیہ"],
    "azzaWaJall": ["عز و جل"],
    "quddisaSirruhu": ["قدس سرہ"],
    "alayhiSalaam": ["علیہ السلام"],
    "alayhimSalaam": ["علیہم السلام"],
    "alayhimaaSalaam": ["علیہما السلام"],
    "alayhaaSalaam": ["علیہا السلام"],
    "alayhiSalaatuWasSalaam": ["علیہ الصلوۃ و السلام", "علیہ الصلاۃ و السلام"],
}


def main():
    font = glyphsLib.GSFont(SOURCE)
    cmap, marks, letters = {}, [], []
    for g in font.glyphs:
        for u in g.unicodes or []:
            cp = int(u, 16)
            cmap[chr(cp)] = g.name
            if 0x0600 <= cp <= 0x06FF or 0xFB50 <= cp <= 0xFDFF:
                kind = unicodedata.category(chr(cp))
                if kind.startswith("M"):
                    marks.append(g.name)
                elif kind.startswith("L"):
                    letters.append(g.name)
    # the language setup turns the space into the Urdu word space before
    # these rules run; accept either
    space = f"[{cmap[' ']} space.urdu]" if "space.urdu" in font.glyphs else cmap[" "]

    def cls(ch):
        names = sorted({cmap[c] for c in ALTERNATIVES.get(ch, ch) if c in cmap})
        return names[0] if len(names) == 1 else "[" + " ".join(names) + "]"

    honorifics = [g for g in PHRASES if g in font.glyphs]
    # the one spelling each phrase is drawn from; other spellings are first
    # brought to it (only inside a matched phrase), so the ligatures need no
    # glyph classes, which would multiply out into tens of thousands of rules
    canon = {}
    for ch, alts in ALTERNATIVES.items():
        for alt in alts[1:]:
            if alt in cmap and ch in cmap:
                canon[cmap[alt]] = cmap[ch] if ch != "آ" else cmap["ا"]
    if "آ" in cmap:
        canon[cmap["آ"]] = cmap["ا"]
    if "space.urdu" in font.glyphs:
        canon["space.urdu"] = cmap[" "]
    canon = {a: b for a, b in canon.items() if a != b}

    def plain_seq(seq):
        out = []
        for s in seq:
            if s.startswith("["):
                names = s[1:-1].split()
                out.append(canon.get(names[0], names[0]) if names[0] in canon else
                           next((n for n in names if n not in canon), names[0]))
            else:
                out.append(canon.get(s, s))
        return out

    out = [
        "# Generated by scripts/honorific-ligatures.py: typed honorifics to their glyphs.",
        "",
        f"@HonorificLetters = [{' '.join(sorted(set(letters) - set(honorifics)))}];",
        f"@HonorificHarakat = [{' '.join(sorted(set(marks) - set(PHRASES)))}];",
        f"@Honorifics = [{' '.join(honorifics)}];",
        "",
        "lookup HonorificCanon {",
    ]
    out += [f"  sub {a} by {b};" for a, b in sorted(canon.items())]
    out += ["} HonorificCanon;", ""]
    forms = []  # (glyph, sequence with classes, plain sequence)
    for glyph in honorifics:
        for phrase in PHRASES[glyph]:
            words = [[cls(ch) for ch in w] for w in phrase.split()]
            # each gap between words may be typed with a space or without
            for gaps in itertools.product(("", space), repeat=len(words) - 1):
                seq = list(words[0])
                for gap, word in zip(gaps, words[1:]):
                    seq += ([gap] if gap else []) + word
                forms.append((glyph, seq, plain_seq(seq)))
    out += ["lookup HonorificLigatures {", "  lookupflag IgnoreMarks;"]
    seen = set()
    for glyph, _, flat in forms:
        if tuple(flat) not in seen:
            seen.add(tuple(flat))
            out.append(f"  sub {' '.join(flat)} by {glyph};")
    out += ["} HonorificLigatures;", ""]

    def guarded(name, seqs, apply):
        lines = [f"lookup {name} {{", "  lookupflag IgnoreMarks;"]
        # longest phrases first, each guarded just before its own rule: a
        # shorter phrase's guard (رضی اللہ عنہ followed by a letter) must not
        # shut out a longer one (رضی اللہ عنہا)
        for seq in sorted(seqs, key=len, reverse=True):
            marked = " ".join(s + "'" for s in seq)
            lines.append(f"  ignore sub @HonorificLetters {marked};")
            lines.append(f"  ignore sub {marked} @HonorificLetters;")
            lines.append("  sub " + " ".join(apply(k, s) for k, s in enumerate(seq)) + ";")
        lines += [f"}} {name};", ""]
        return lines

    # 1. inside a phrase, bring every letter and space to its plain spelling
    needs = [seq for _, seq, _ in forms if any(s.startswith("[") or s in canon for s in seq)]
    out += guarded("HonorificNormalize", needs,
                   lambda k, s: f"{s}' lookup HonorificCanon" if s.startswith("[") or s in canon else f"{s}'")
    # 2. the plain phrase becomes its glyph
    plains = []
    for _, _, flat in forms:
        if flat not in plains:
            plains.append(flat)
    out += guarded("HonorificPhrases", plains,
                   lambda k, s: f"{s}' lookup HonorificLigatures" if k == 0 else f"{s}'")
    out += [
        "# harakat typed inside a phrase are left after its glyph: empty them",
        "lookup HonorificHarakat {",
        f"  sub [@Honorifics {MARK}] @HonorificHarakat' by {MARK};",
        "} HonorificHarakat;",
        "",
        "feature ccmp {",
        "  lookup HonorificNormalize;",
        "  lookup HonorificPhrases;",
        "  lookup HonorificHarakat;",
        "} ccmp;",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"{len(forms)} phrase forms for {len(honorifics)} honorifics -> {OUT}")


if __name__ == "__main__":
    main()
